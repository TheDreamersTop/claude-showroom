import { chromium } from '/opt/node22/lib/node_modules/playwright/index.mjs';
const url = process.argv[2];
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist','--disable-component-update'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const out = [];
page.on('console', m => out.push(`[${m.type()}] ${m.text()}`));
page.on('pageerror', e => out.push(`[pageerror] ${e.message}`));
page.on('response', r => { if (r.status() >= 400) out.push(`[http ${r.status()}] ${r.url()}`); });
page.on('requestfailed', r => out.push(`[reqfail] ${r.url()}`));
await page.goto(url); await page.waitForFunction('window.__ready === true', null, { timeout: 120000 });
await page.waitForTimeout(3000);
await page.mouse.click(700, 400); await page.waitForTimeout(4000);
await page.mouse.move(900, 200); await page.waitForTimeout(4000);
await page.keyboard.press('KeyV'); await page.waitForTimeout(1500); await page.keyboard.press('KeyV');
await page.keyboard.down('KeyB'); await page.waitForTimeout(1500); await page.keyboard.up('KeyB');
await page.keyboard.press('Space'); await page.waitForTimeout(6000);
await page.keyboard.press('Space'); await page.waitForTimeout(4000);
await page.reload(); await page.waitForFunction('window.__ready === true', null, { timeout: 120000 }); await page.waitForTimeout(2000);
console.log(out.filter(l => !/GPU stall due to ReadPixels/.test(l)).join('\n') || 'no console output');
console.log('phase', await page.evaluate('window.__phase'));
await browser.close();
